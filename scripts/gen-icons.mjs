#!/usr/bin/env node
/**
 * Regenerates src/ui/icons/lucide.generated.ts from Lucide's icon nodes.
 * The Claude Design canvas draws every icon with Lucide geometry, so the app
 * does too. Lucide is ISC-licensed (src/ui/icons/LICENSE-lucide).
 *
 *   npm i --no-save lucide-static && node scripts/gen-icons.mjs node_modules/lucide-static/icon-nodes.json
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** Our icon name → Lucide icon name. Add a line here to add an icon. */
