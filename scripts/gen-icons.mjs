  filter: 'funnel', sort: 'arrow-up-down', star: 'star', pin: 'pin', mic: 'mic', send: 'send', share: 'share-2', lock: 'lock',
  link: 'link', paperclip: 'paperclip', refresh: 'refresh-cw', download: 'download', transfer: 'arrow-left-right',
  'plus-circle': 'circle-plus', 'x-circle': 'circle-x', 'check-circle': 'circle-check', circle: 'circle',
  bell: 'bell', calendar: 'calendar', clock: 'clock-4', repeat: 'repeat', alert: 'circle-alert', warning: 'triangle-alert', info: 'info',
  moon: 'moon', sun: 'sun', eye: 'eye', target: 'target', inbox: 'inbox', hourglass: 'hourglass',
  tag: 'tag', comment: 'message-square', file: 'file-text', folder: 'folder', book: 'book-open', list: 'list', archive: 'archive',
